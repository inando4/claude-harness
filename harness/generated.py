"""Exact receipts for Gradle outputs created by configured controller commands.

Never adopt caches merely because they are ignored, or generated by an IDE.
"""
from pathlib import Path


def candidates(h,s,step):
    command=step.get('command',[])
    if not command or Path(command[0]).name not in {'gradle','gradlew'}:return []
    name=step.get('repo') or h.config().get('primaryRepository','main')
    tree=h.repository_root(s,name);cwd=h.safe_path(tree,step.get('cwd','.'))
    return [(name,tree,cwd/'.gradle'),(name,tree,cwd/'build')]


def before(h,s,step):
    result=[]
    if not s.get('publication'):return result
    for name,tree,directory in candidates(h,s,step):
        if directory.is_symlink() or not directory.resolve().is_relative_to(tree.resolve()):continue
        initial={str(p.relative_to(tree)) for p in directory.rglob('*')} if directory.exists() else set()
        prior=s['publication']['repos'][name].get('generatedFiles',{})
        renewable={relative for relative in initial if relative in prior and
                   (tree/relative).is_file() and not (tree/relative).is_symlink() and
                   (tree/relative).resolve().is_relative_to(directory.resolve()) and
                   h.sha(tree/relative)==prior[relative]['sha256']}
        result.append((name,tree,directory,initial-renewable))
    return result


def after(h,s,baseline):
    for name,tree,directory,initial in baseline:
        if directory.is_symlink() or not directory.resolve().is_relative_to(tree.resolve()):continue
        tracked=set(h.publication_module().out(h,tree,'ls-files','--',str(directory.relative_to(tree))).splitlines())
        records=s['publication']['repos'][name].setdefault('generatedFiles',{})
        for path in directory.rglob('*'):
            relative=str(path.relative_to(tree))
            # Existing data and links cannot gain cleanup permission by running a tool.
            if relative in initial or relative in tracked or path.is_symlink() or not path.is_file():continue
            if not path.resolve().is_relative_to(directory.resolve()):continue
            records[relative]={'sha256':h.sha(path),'tool':'gradle','attempt':s.get('attempt')}
    if baseline:h.save(s,'generated_outputs_recorded')
